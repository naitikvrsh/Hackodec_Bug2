import { Router, Request, Response } from 'express';
import fs from 'fs';
import path from 'path';
import { exec } from 'child_process';
import { MLSemanticClassifier } from '../firewall/mlClassifier.js';
import { getDataDir, getModelsDir, getRootDir } from '../config.js';

export const mlRouter = Router();

// Helper to locate python binary (.venv or system)
function getPythonExecutable(): string {
  const rootDir = getRootDir();
  const venvPythonWin = path.join(rootDir, '.venv', 'Scripts', 'python.exe');
  const venvPythonUnix = path.join(rootDir, '.venv', 'bin', 'python');
  if (fs.existsSync(venvPythonWin)) return `"${venvPythonWin}"`;
  if (fs.existsSync(venvPythonUnix)) return venvPythonUnix;
  return 'python';
}

/**
 * GET /api/ml/status
 * Returns live ML model readiness, version, dataset counts, and training timestamp.
 */
mlRouter.get('/status', (_req: Request, res: Response) => {
  const classifier = MLSemanticClassifier.getInstance();
  const metadata = classifier.getModelMetadata();

  let datasetSizes = {
    train: 97,
    validation: 32,
    test: 42,
    hard_negatives: 19,
    demonstration: 40,
  };

  const dataDir = getDataDir();
  const metaFile = path.join(dataDir, 'training_metadata.json');
  if (fs.existsSync(metaFile)) {
    try {
      const parsed = JSON.parse(fs.readFileSync(metaFile, 'utf8'));
      if (parsed.dataset_sizes) datasetSizes = parsed.dataset_sizes;
    } catch (e) {
      // ignore
    }
  }

  res.json({
    status: classifier.isReady() ? 'ready' : 'missing',
    isReady: classifier.isReady(),
    version: metadata.version || '1.0.0',
    last_trained: metadata.last_trained || metadata.trained_timestamp || null,
    architecture: metadata.architecture || 'Calibrated Dual-Head Multi-Scale N-Gram Logistic Classifier',
    features_count: metadata.features_count || 5044,
    categories_count: metadata.categories_count || 20,
    dataset_sizes: datasetSizes,
    metrics: metadata.metrics || null,
  });
});

/**
 * GET /api/ml/demonstration-cases
 * Returns the 40 cases (20 attack + 20 normal) with real predictions generated by the ML model.
 */
mlRouter.get('/demonstration-cases', (_req: Request, res: Response) => {
  const classifier = MLSemanticClassifier.getInstance();
  const demoPath = path.join(getDataDir(), 'demonstration_40.json');

  if (!fs.existsSync(demoPath)) {
    return res.status(404).json({ error: 'Demonstration cases dataset not found' });
  }

  try {
    const rawCases: Array<{
      id: string;
      text: string;
      expectedLabel: 'MALICIOUS' | 'BENIGN';
      category: string;
      split: 'test' | 'train' | 'validation';
      rationale: string;
    }> = JSON.parse(fs.readFileSync(demoPath, 'utf8'));

    // Compute actual real-time predictions using the trained model
    const evaluatedCases = rawCases.map((c) => {
      const pred = classifier.classify(c.text);
      const isCorrect = pred.label === c.expectedLabel;
      return {
        id: c.id,
        text: c.text,
        expectedLabel: c.expectedLabel,
        category: c.category,
        split: c.split,
        rationale: c.rationale,
        modelPrediction: pred.label,
        predictedCategory: pred.category,
        predictionConfidence: pred.confidence,
        probabilities: pred.probabilities,
        isCorrect,
        explanation: pred.explanation,
        latencyMs: pred.latencyMs,
      };
    });

    const total = evaluatedCases.length;
    const correctCount = evaluatedCases.filter((c) => c.isCorrect).length;
    const attacks = evaluatedCases.filter((c) => c.expectedLabel === 'MALICIOUS');
    const normals = evaluatedCases.filter((c) => c.expectedLabel === 'BENIGN');

    res.json({
      total,
      attackCount: attacks.length,
      normalCount: normals.length,
      accuracy: Math.round((correctCount / max(1, total)) * 1000) / 10,
      cases: evaluatedCases,
    });
  } catch (err: any) {
    res.status(500).json({ error: `Failed to evaluate demonstration cases: ${err.message}` });
  }
});

function max(a: number, b: number) {
  return a > b ? a : b;
}

/**
 * GET /api/ml/evaluation
 * Returns held-out evaluation report, confusion matrix, and per-category metrics.
 */
mlRouter.get('/evaluation', (_req: Request, res: Response) => {
  const reportPath = path.join(getModelsDir(), 'aegisguard-classifier', 'evaluation_report.json');
  if (fs.existsSync(reportPath)) {
    try {
      const report = JSON.parse(fs.readFileSync(reportPath, 'utf8'));
      return res.json(report);
    } catch (e: any) {
      return res.status(500).json({ error: `Failed to read evaluation report: ${e.message}` });
    }
  }
  res.status(404).json({ error: 'Evaluation report not found. Run python -m training.evaluate.' });
});

/**
 * POST /api/ml/classify
 * Classifies arbitrary input text using the trained semantic classifier.
 */
mlRouter.post('/classify', (req: Request, res: Response) => {
  const { text } = req.body;
  if (typeof text !== 'string') {
    return res.status(400).json({ error: 'Field "text" string is required' });
  }

  const classifier = MLSemanticClassifier.getInstance();
  const prediction = classifier.classify(text);
  res.json(prediction);
});

/**
 * POST /api/ml/train
 * Executes real training pipeline via child process and reloads model weights.
 */
mlRouter.post('/train', (_req: Request, res: Response) => {
  const pythonCmd = getPythonExecutable();
  const rootDir = getRootDir();
  const trainCmd = `${pythonCmd} -m training.train`;

  console.log(`[AEGISGUARD ML] Triggering training process: ${trainCmd} in ${rootDir}`);

  exec(trainCmd, { cwd: rootDir }, (error, stdout, stderr) => {
    if (error) {
      console.error('[AEGISGUARD ML] Training process failed:', stderr || error.message);
      return res.status(500).json({
        success: false,
        error: `Training failed: ${stderr || error.message}`,
        stdout,
      });
    }

    // Reload model in-memory
    const classifier = MLSemanticClassifier.getInstance();
    const reloaded = classifier.reloadModel();

    console.log('[AEGISGUARD ML] Training completed and model reloaded successfully.');

    res.json({
      success: true,
      message: 'Model trained and reloaded successfully.',
      reloaded,
      stdout,
      metadata: classifier.getModelMetadata(),
    });
  });
});
